import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
const source=new URL(process.env.DATABASE_URL);
const suffix=Date.now();const copyName=`fsin_verify_upgrade_${suffix}`,cleanName=`fsin_verify_clean_${suffix}`;
const bin=process.env.PG_BIN??'C:/Program Files/PostgreSQL/17/bin';
const env={...process.env,PGHOST:source.hostname,PGPORT:source.port||'5432',PGUSER:decodeURIComponent(source.username),PGPASSWORD:decodeURIComponent(source.password)};
const run=(name,args)=>{const r=spawnSync(`${bin}/${name}.exe`,args,{env,encoding:'utf8'});if(r.status!==0)throw new Error(`${name}: ${r.stderr}`);};
mkdirSync('.verification',{recursive:true});
run('pg_dump',['--format=custom','--file=.verification/before.dump','--dbname',source.pathname.slice(1)]);
for(const name of [copyName,cleanName])run('createdb',[name]);
run('pg_restore',['--no-owner','--no-privileges','--dbname',copyName,'.verification/before.dump']);
const target=new URL(source);target.pathname='/'+copyName;
const clean=new URL(source);clean.pathname='/'+cleanName;
writeFileSync('.verification/targets.json',JSON.stringify({source:source.toString(),upgrade:target.toString(),clean:clean.toString()}));
const p=new PrismaClient({datasources:{db:{url:target.toString()}}});
const tables=['users','students','groups','attendance_sheets','attendance_records','student_group_histories','student_status_histories','student_course_histories','audit_logs','educational_programs','directions','user_roles','user_group_scopes','user_direction_scopes'];
const before={};for(const table of tables) before[table]=await p.$queryRawUnsafe(`SELECT * FROM "${table}" ORDER BY 1`);
writeFileSync('.verification/before.json',JSON.stringify(before));await p.$disconnect();
console.log('Created isolated upgrade and empty verification databases. Source unchanged.');
